// Shared page shell for the generated /training/ pages (used by build-training.mjs and build-catalog.mjs).
import fs from 'node:fs';
import path from 'node:path';
export const SITE = path.resolve('site');
const family = JSON.parse(fs.readFileSync(path.join(SITE, 'family.json'), 'utf8'));
export const base = family.home.replace(/\/$/, '');
export const site = JSON.parse(fs.readFileSync(path.join(SITE, 'site.json'), 'utf8'));
export const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
/* ---------- page shell ---------- */

export function page({ title, description, canonicalPath, ld, body, section = 'training', css = [] }) {
  const url = base + canonicalPath;
  return `<!doctype html>
<!-- Generated by tools/build-training.mjs from site/training/training.json. Edit the data, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(description)}">
  <meta name="theme-color" content="#f2b631">
  <link rel="canonical" href="${url}">
  <meta property="og:site_name" content="Intellica">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(description)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="https://meeting-mind.com/assets/og.png">
  <meta name="twitter:card" content="summary_large_image">
${ld ? `  <script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>\n` : ''}  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <link rel="icon" href="/assets/favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">
  <script src="/kit/theme-init.js"></script>
  <link rel="stylesheet" href="/kit/tokens.css">
  <link rel="stylesheet" href="/kit/shell.css">
  <link rel="stylesheet" href="/training/training.css">
  <link rel="stylesheet" href="/training/arc42/course/board.css">
${css.map((c) => `  <link rel="stylesheet" href="${c}">\n`).join('')}</head>
<body data-tab="training" data-generated="training" data-section="${section}">
  <a class="skip-link" href="#main">Skip to content</a>
  <div id="shell-header"></div>

  <main id="main" class="container tr">
${body}
  </main>

  <div id="shell-footer"></div>
  <script type="module" src="/kit/shell.js"></script>
  <script type="module" src="/training/training.js"></script>
</body>
</html>
`;
}

export const kicker = (n, label) => `<p class="kicker"><span class="kn">${String(n).padStart(2, '0')}</span>${esc(label)}</p>`;
export const cols = (items, cls = '') => `<div class="cols ${cls}">${items.map((i) => `<div><h3>${esc(i.title)}</h3><p>${esc(i.text)}</p></div>`).join('')}</div>`;
