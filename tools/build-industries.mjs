#!/usr/bin/env node
// Generates /industries/<sector>/index.html from site/industries/industries.json.
// Real HTML, no JavaScript needed. Reuses the consulting page styles. Safe to run repeatedly.
import fs from 'node:fs';
import path from 'node:path';

const SITE = path.resolve('site');
const d = JSON.parse(fs.readFileSync(path.join(SITE, 'industries', 'industries.json'), 'utf8'));
const family = JSON.parse(fs.readFileSync(path.join(SITE, 'family.json'), 'utf8'));
const site = JSON.parse(fs.readFileSync(path.join(SITE, 'site.json'), 'utf8'));
const base = family.home.replace(/\/$/, '');
const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const wa = (t) => `https://wa.me/${site.whatsapp}?text=${encodeURIComponent(t)}`;
const byId = Object.fromEntries(family.products.map((p) => [p.id, p]));

for (const s of d.sectors) {
  const url = `${base}/industries/${s.id}/`;
  const title = `${s.title}: AI engineering you can check | Intellica`;
  const desc = s.lead;
  const others = d.sectors.filter((o) => o.id !== s.id);
  const body = `
    <section class="hero k-hero" aria-labelledby="k-title">
      <div class="hero-copy">
        <p class="eyebrow">${esc(s.kicker)}</p>
        <h1 id="k-title">${esc(s.h1)}</h1>
        <p class="lead">${esc(s.lead)}</p>
        <div class="actions">
          <a class="btn btn-primary" href="/consulting/#assess">Check your AI readiness</a>
          <a class="btn btn-ghost" href="#contact">Talk to sales</a>
        </div>
      </div>
      <aside class="hero-visual k-sample" aria-label="Frameworks in play">
        <span class="k-sample-k">Frameworks in play</span>
        <ul class="k-fw">${s.frameworks.map((f) => `<li>${esc(f)}</li>`).join('')}</ul>
      </aside>
    </section>

    <section class="block" aria-labelledby="p-title">
      <p class="kicker-m">01 · What is different here</p>
      <h2 id="p-title">The pressures we see in ${esc(s.title.toLowerCase())}</h2>
      <div class="k-habits">
${s.pressures.map((x) => `        <div><h3>${esc(x.t)}</h3><p>${esc(x.p)}</p></div>`).join('\n')}
      </div>
    </section>

    <section class="block" aria-labelledby="h-title">
      <p class="kicker-m">02 · How we help</p>
      <h2 id="h-title">Where we start</h2>
      <div class="k-eng">
${s.help.map((x, i) => `        <article class="k-offer">
          <header><span class="k-n">0${i + 1}</span></header>
          <h3>${esc(x.t)}</h3>
          <p class="k-pitch">${esc(x.p)}</p>
          <p class="k-cta"><a href="${x.href}">Read more</a></p>
        </article>`).join('\n')}
      </div>
    </section>

    <section class="block k-systems" aria-labelledby="sys-title">
      <p class="kicker-m">03 · Systems</p>
      <h2 id="sys-title">Systems that fit this work</h2>
      <ul class="k-sys-list">
${s.systems.filter((id) => byId[id]).map((id) => `        <li><a href="${byId[id].url}"><strong>${esc(byId[id].name)}</strong><span>${esc(byId[id].short || '')}</span></a></li>`).join('\n')}
      </ul>
    </section>

    <section class="block" aria-labelledby="o-title">
      <p class="kicker-m" id="o-title">Other sectors</p>
      <ul class="inline-list">${others.map((o) => `<li><a href="/industries/${o.id}/">${esc(o.title)}</a></li>`).join('')}</ul>
    </section>

    <section class="cta-band" id="contact" aria-labelledby="contact-title">
      <div><h2 id="contact-title">Talk to sales</h2><p>Tell us what you need to be able to prove. We reply on WhatsApp.</p></div>
      <div class="actions"><a class="btn btn-primary" href="${wa(`Hello, I would like to talk about AI engineering for ${s.title.toLowerCase()}.`)}">Contact sales</a></div>
    </section>`;
  const ld = { '@context': 'https://schema.org', '@type': 'WebPage', name: title, url, description: desc, isPartOf: { '@type': 'WebSite', name: 'Intellica', url: base + '/' } };
  const html = `<!doctype html>
<!-- Generated by tools/build-industries.mjs from site/industries/industries.json. Edit the data, not this file. -->
<html lang="en">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>${esc(title)}</title>
  <meta name="description" content="${esc(desc)}">
  <meta name="theme-color" content="#00C8FF">
  <link rel="canonical" href="${url}">
  <meta property="og:site_name" content="Intellica">
  <meta property="og:type" content="website">
  <meta property="og:title" content="${esc(title)}">
  <meta property="og:description" content="${esc(desc)}">
  <meta property="og:url" content="${url}">
  <meta property="og:image" content="https://meeting-mind.com/assets/og.png">
  <meta name="twitter:card" content="summary_large_image">
  <script type="application/ld+json">${JSON.stringify(ld).replace(/</g, '\\u003c')}</script>
  <link rel="icon" href="/assets/favicon.svg" type="image/svg+xml">
  <link rel="icon" href="/assets/favicon-32.png" type="image/png" sizes="32x32">
  <link rel="apple-touch-icon" href="/assets/apple-touch-icon.png">
  <script src="/kit/theme-init.js"></script>
  <link rel="stylesheet" href="/kit/tokens.css">
  <link rel="stylesheet" href="/kit/shell.css">
  <link rel="stylesheet" href="/consulting/consulting.css">
</head>
<body data-tab="industries" data-generated="industries" data-section="consulting">
  <a class="skip-link" href="#main">Skip to content</a>
  <div id="shell-header"></div>
  <main id="main" class="container k">${body}
  </main>
  <div id="shell-footer"></div>
  <script type="module" src="/kit/shell.js"></script>
</body>
</html>
`;
  fs.mkdirSync(path.join(SITE, 'industries', s.id), { recursive: true });
  fs.writeFileSync(path.join(SITE, 'industries', s.id, 'index.html'), html);
}
console.log(`built ${d.sectors.length} industry pages`);
